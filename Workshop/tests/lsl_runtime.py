"""Execute the actual LSL ASTs in a small deterministic event harness.

Tailslide checks syntax/types. This harness models only the LSL subset used by
these scripts, link messages, chat and durable linkset data. It is NOT SL/Mono.
Used by test_playback_buttons.py; ASTs are generated by check_playback_buttons.cjs.
"""
import json
import re
import unittest
import uuid
from collections import deque
from pathlib import Path

NULL = '00000000-0000-0000-0000-000000000000'
OWNER = '11111111-1111-1111-1111-111111111111'


class Key(str):
    def __bool__(self):
        try:
            return uuid.UUID(self).int != 0
        except ValueError:
            return False


def cast(value, kind):
    if kind == 'key':
        return Key(str(value))
    if kind == 'string':
        return str(value)
    if kind == 'integer':
        try:
            return int(value)
        except (ValueError, TypeError):
            return 0
    if kind == 'float':
        return float(value)
    return value


def default(kind):
    return {'key': Key(''), 'list': [], 'string': '', 'integer': 0,
            'float': 0.0, 'vector': (0., 0., 0.), 'rotation': (0., 0., 0., 1.)}.get(kind)


class Node:
    def __init__(self, text):
        self.text = text
        self.children = []
        match = re.search(r' \[(none|integer|float|string|key|list|vector|rotation)\]', text)
        self.kind = text[:match.start()] if match else text
        self.type = match[1] if match else 'none'

    @property
    def name(self):
        return re.search(r'identifier "([^"]+)"', self.text)[1]


def tree(text):
    root = None
    stack = []
    for line in text.splitlines():
        if not line.strip():
            continue
        depth = (len(line) - len(line.lstrip())) // 2
        node = Node(line.strip())
        while len(stack) > depth:
            stack.pop()
        if stack:
            stack[-1].children.append(node)
        else:
            root = node
        stack.append(node)
    return root


class Returned(Exception):
    pass


class Jump(Exception):
    pass


class World:
    def __init__(self):
        self.scripts = []
        self.storage = {}
        self.queue = deque()
        self.logs = []
        self.radio = []
        self.fail_storage = set()
        self.description = {}
        self.now = 0

    def drain(self, limit=2000):
        count = 0
        while self.queue:
            script, event, args = self.queue.popleft()
            if script in self.scripts:
                script.call(event, args)
            count += 1
            if count > limit:
                raise AssertionError('Event feedback loop')

    def tick(self):
        self.now += 5
        for script in list(self.scripts):
            if script.timer and script.due <= self.now:
                script.due = self.now + script.timer
                self.queue.append((script, 'timer', []))
        self.drain()


TREES = {name: tree(text) for name, text in json.loads(Path(__file__).with_name('lsl_asts.json').read_text()).items()}


class Script:
    def __init__(self, world, file, object_id, overrides=None):
        self.world, self.file, self.object = world, file, Key(object_id)
        self.global_vars, self.functions = {}, {}
        self.timer = 0
        self.due = 0
        for group in TREES[file].children:
            for node in group.children:
                if node.kind == 'global var':
                    ident, value = node.children
                    self.global_vars[ident.name] = cast(self.eval(value, {}), ident.type) if value.kind != 'null' else default(ident.type)
                elif node.kind == 'global func':
                    self.functions[node.children[0].name] = (node.children[1], node.children[2])
                elif node.kind == 'state':
                    for event in node.children[1].children:
                        self.functions[event.children[0].name] = (event.children[1], event.children[2])
        self.global_vars.update(overrides or {})
        world.scripts.append(self)
        if 'state_entry' in self.functions:
            self.call('state_entry', [])

    def restart(self, overrides=None):
        self.world.scripts.remove(self)
        return Script(self.world, self.file, self.object, overrides)

    def call(self, name, args):
        if name not in self.functions:
            return self.builtin(name, args)
        declaration, body = self.functions[name]
        local = {n.name: cast(v, n.type) for n, v in zip(declaration.children, args)}
        try:
            self.eval(body, local)
        except Returned as returned:
            return returned.args[0]

    def eval(self, n, env):
        kind, c = n.kind, n.children
        if kind == 'null':
            return None
        if kind.startswith('identifier'):
            if n.name in env:
                return env[n.name]
            if n.name in self.global_vars:
                return self.global_vars[n.name]
            constant = re.search(r'\(cv=(.*)\) \(\d+,\d+\)$', n.text)
            if constant and constant[1]:
                return self.constant(constant[1])
            raise AssertionError('Unknown identifier ' + n.text)
        if kind.startswith(('integer constant:', 'float constant:', 'string constant:', 'vector constant:')):
            return self.constant(kind)
        if kind.startswith('lvalue expression') or kind in ('constant expression', 'parenthesis expression'):
            return self.eval(c[0], env)
        if kind == 'typecast expression':
            return cast(self.eval(c[0], env), n.type)
        if kind == 'list expression':
            return [self.eval(child, env) for child in c]
        if kind == 'vector expression':
            return tuple(self.eval(child, env) for child in c)
        if kind == 'function call':
            # LSL evaluates argument expressions from right to left.
            args = [None] * len(c[1].children)
            for i in reversed(range(len(args))):
                args[i] = self.eval(c[1].children[i], env)
            return self.call(c[0].name, args)
        if kind in ('declaration', 'global var'):
            env[c[0].name] = cast(self.eval(c[1], env), c[0].type) if c[1].kind != 'null' else default(c[0].type)
            return
        if kind.startswith('binary expression:'):
            op = kind.split("'")[1]
            right = self.eval(c[1], env)
            if op in ('=', '+=', '-=', '*=', '/='):
                name = c[0].children[0].name
                target = env if name in env else self.global_vars
                if op == '+=':
                    right = target[name] + (right if isinstance(right,list) else [right]) if isinstance(target[name],list) else target[name] + right
                if op == '-=':
                    right = target[name] - right
                if op == '*=':
                    right = target[name] * right
                if op == '/=':
                    right = target[name] / right
                target[name] = cast(right, n.type)
                return target[name]
            left = self.eval(c[0], env)
            if op == '+' and (isinstance(left,list) or isinstance(right,list)):
                return (left if isinstance(left,list) else [left]) + (right if isinstance(right,list) else [right])
            operations = {
                '+': lambda: left + right, '-': lambda: left - right,
                '*': lambda: left * right, '/': lambda: left / right,
                '%': lambda: left % right, '==': lambda: int(left == right),
                '!=': lambda: int(left != right), '<': lambda: int(left < right),
                '>': lambda: int(left > right), '<=': lambda: int(left <= right),
                '>=': lambda: int(left >= right), '||': lambda: int(bool(left) or bool(right)),
                '&&': lambda: int(bool(left) and bool(right)), '&': lambda: left & right, '|': lambda: left | right,
            }
            return cast(operations[op](), n.type)
        if kind.startswith('unary expression:'):
            op = kind.split("'")[1]
            value = self.eval(c[0], env)
            if op == '!':
                return int(not value)
            if op == '-':
                return -value
            if op == '+':
                return value
            if op in ('++ (pre)', '++ (post)'):
                name = c[0].children[0].name
                target = env if name in env else self.global_vars
                target[name] += 1
                return target[name] if op == '++ (pre)' else target[name]-1
            raise AssertionError(op)
        if kind in ('compound statement', 'ast node list'):
            i = 0
            while i < len(c):
                try:
                    self.eval(c[i], env)
                except Jump as jump:
                    found = [j for j, child in enumerate(c) if child.kind == 'label' and child.children[0].name == jump.args[0]]
                    if not found:
                        raise
                    i = found[0]
                i += 1
            return
        if kind == 'expression statement':
            return self.eval(c[0], env)
        if kind == 'if':
            return self.eval(c[1] if self.eval(c[0], env) else c[2], env)
        if kind == 'for':
            self.eval(c[0], env)
            iterations = 0
            while self.eval(c[1], env):
                self.eval(c[3], env)
                self.eval(c[2], env)
                iterations += 1
                if iterations > 1000:
                    raise AssertionError('Infinite loop')
            return
        if kind == 'return':
            raise Returned(self.eval(c[0], env) if c else None)
        if kind.startswith('jump'):
            raise Jump(c[0].name)
        if kind == 'label':
            return
        raise AssertionError('Unsupported AST ' + n.text)

    @staticmethod
    def constant(text):
        kind, value = text.split(' constant: ', 1)
        if kind == 'string':
            value = json.loads(value)
            # This Windows parser emits JSON flag UTF-8 bytes decoded as cp1252.
            flags = {chr(i).encode('utf-8').decode('cp1252'): chr(i) for i in (0xfdd2, 0xfdd3, 0xfdd4)}
            return flags.get(value, value)
        if kind == 'integer':
            return int(value)
        if kind == 'float':
            return float(value)
        if kind == 'vector':
            return tuple(float(x) for x in value.strip('<>').split(','))
        raise AssertionError(text)

    def builtin(self, name, a):
        w = self.world
        if name == 'llGetKey': return self.object
        if name == 'llGetOwner': return Key(OWNER)
        if name == 'llGetOwnerKey': return Key(OWNER)
        if name == 'llGenerateKey': return Key(str(uuid.uuid4()))
        if name == 'llGetLinkNumber': return 1
        if name == 'llGetObjectDesc': return w.description.get(self.object, '1')
        if name == 'llSetObjectDesc': w.description[self.object] = a[0]; return
        if name == 'llSetText': return
        if name == 'llOwnerSay': w.logs.append((self.object, a[0])); return
        if name == 'llListen': return 1
        if name == 'llListenRemove': return
        if name == 'llGetTime': return w.now
        if name == 'llSetTimerEvent': self.timer = a[0]; self.due = w.now + a[0]; return
        if name == 'llLinksetDataRead': return w.storage.get((self.object, a[0]), '')
        if name == 'llLinksetDataWrite':
            if self.object in w.fail_storage or (self.object, a[0]) in w.fail_storage: return 1
            if w.storage.get((self.object, a[0])) == a[1]: return 5
            w.storage[self.object, a[0]] = a[1]
            return 0
        if name == 'llGetListLength': return len(a[0])
        if name in ('llList2String', 'llList2Key', 'llList2Integer'):
            value = a[0][a[1]] if -len(a[0]) <= a[1] < len(a[0]) else ''
            return cast(value, {'llList2String':'string', 'llList2Key':'key', 'llList2Integer':'integer'}[name])
        if name == 'llListReplaceList': return a[0][:a[2]] + a[1] + a[0][a[3]+1:]
        if name == 'llDeleteSubList': return a[0][:a[1]] + a[0][a[2]+1:]
        if name == 'llList2List': return a[0][a[1]:a[2]+1]
        if name == 'llListFindList':
            return next((i for i in range(len(a[0])) if a[0][i:i+len(a[1])] == a[1]), -1)
        if name == 'llListSort':
            return sum(sorted([a[0][i:i+a[1]] for i in range(0, len(a[0]), a[1])], key=lambda x:x[0]), [])
        if name == 'llList2Json': return json.dumps(a[1], separators=(',', ':'), ensure_ascii=False)
        if name == 'llJson2List':
            try:
                return json.loads(a[0])
            except ValueError:
                return []
        if name == 'llDumpList2String': return a[1].join(str(x) for x in a[0])
        if name == 'llParseStringKeepNulls': return re.split('|'.join(re.escape(x) for x in a[1]), a[0])
        if name == 'llToLower': return a[0].lower()
        if name == 'llStringTrim': return a[0].strip()
        if name == 'llMessageLinked':
            for script in list(w.scripts):
                if script.object == self.object and 'link_message' in script.functions:
                    w.queue.append((script, 'link_message', [1, a[1], a[2], a[3]]))
            return
        if name in ('llRegionSayTo', 'llWhisper'):
            if name == 'llRegionSayTo': target, channel, text = a
            else: channel, text = a; target = None
            w.radio.append((self.object, target, channel, text))
            for script in list(w.scripts):
                if script.object != self.object and (target is None or script.object == target) and 'listen' in script.functions:
                    w.queue.append((script, 'listen', [channel, '', self.object, text]))
            return
        raise AssertionError('Unsupported builtin ' + name)


